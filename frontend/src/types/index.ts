// ============ 课程相关类型 ============

export interface Course {
  id: string
  name: string
  domain: string        // 领域：计算机/医学/法律/生物/物理/数学/其他
  description: string
  customTerms: string[] // 用户自定义术语表
  courseType: 'online' | 'offline'  // 课程类型：线上网课 / 线下课堂
  language: string      // 识别语言：auto / en / zh / ja / ...
  createdAt: number
  updatedAt: number
  videoCount: number
  wordCount: number
}

export interface CourseConfig {
  domain: string
  customTerms: string[]
  courseType: 'online' | 'offline'
  language: string             // 识别语言：auto / en / zh / ja / ...
  autoExtractTerms: boolean  // 是否自动提取术语
  ollamaModel: string         // 使用的 Ollama 模型
}

// ============ 字幕相关类型 ============

export interface SubtitleWord {
  word: string
  start: number      // 毫秒
  end: number        // 毫秒
  confidence: number
}

export interface SubtitleLine {
  id: string
  text: string
  words: SubtitleWord[]
  start: number
  end: number
  isFinal: boolean   // 是否为最终结果（非临时）
}

// ============ 词典相关类型 ============

export interface VocabularyEntry {
  id: string
  word: string            // 原词
  translation: string     // 中文释义
  definition: string      // 英文/中文详细定义
  domain: string          // 所属领域
  contextSentence: string // 来源字幕句子
  sourceSubtitleId: string
  courseId: string
  isAutoGenerated: boolean // 是否 AI 生成
  isMemorized: boolean     // 是否已掌握
  createdAt: number
  reviewedAt: number
  reviewCount: number
}

// ============ 视频相关类型 ============

export interface VideoSource {
  id: string
  courseId: string
  title: string
  filePath?: string       // 本地文件路径
  url?: string            // 在线 URL
  duration: number        // 秒
  createdAt: number
}

// ============ WebSocket 消息类型 ============

export type WSMessage =
  | { type: 'subtitle'; data: SubtitleLine }
  | { type: 'term_extracted'; data: VocabularyEntry }
  | { type: 'asr_status'; data: { status: 'listening' | 'processing' | 'loading' | 'idle' | 'error'; message?: string } }
  | { type: 'error'; data: { message: string } }

// ============ 应用状态 ============

export type ASRStatus = 'idle' | 'listening' | 'processing' | 'loading' | 'error'
