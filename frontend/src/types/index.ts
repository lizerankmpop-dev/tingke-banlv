// ============ 课程相关类型 ============

export interface Course {
  id: string
  name: string
  domain: string        // 领域：计算机/医学/法律/生物/物理/数学/其他
  description: string
  customTerms: string[] // 用户自定义术语表
  courseType: 'online' | 'offline'  // 课程类型：线上网课 / 线下课堂
  language: string      // 识别语言：auto / en / zh / ja / ...
  createdAt: number
  updatedAt: number
  videoCount: number
  wordCount: number
}

export interface CourseConfig {
  domain: string
  customTerms: string[]
  courseType: 'online' | 'offline'
  language: string             // 识别语言：auto / en / zh / ja / ...
  autoExtractTerms: boolean  // 是否自动提取术语
  ollamaModel: string         // 使用的 Ollama 模型
}

// ============ 字幕相关类型 ============

export interface SubtitleWord {
  word: string
  start: number      // 毫秒
  end: number        // 毫秒
  confidence: number
}

export interface SubtitleLine {
  id: string
  text: string
  words: SubtitleWord[]
  start: number
  end: number
  isFinal: boolean   // 是否为最终结果（非临时）
}

// ============ 词典相关类型 ============

export interface VocabularyEntry {
  id: string
  word: string            // 原词
  translation: string     // 中文释义
  definition: string      // 英文/中文详细定义
  domain: string          // 所属领域
  contextSentence: string // 来源字幕句子
  sourceSubtitleId: string
  courseId: string
  isAutoGenerated: boolean // 是否 AI 生成
  isMemorized: boolean     // 是否已掌握
  createdAt: number
  reviewedAt: number
  reviewCount: number
  /** 来源字幕在音频中的时间点（毫秒），导出的 SRT 靠它定位 */
  sourceSrtTime?: number
  // ---- 间隔重复排程（SM2）----
  /** 已成功复习次数 */
  repetitions?: number
  /** 难度因子，1.3~5.0，默认 2.5 */
  efactor?: number
  /** 当前复习间隔（天，允许小数） */
  interval?: number
  /** 下次到期时间戳（毫秒）；<= now 即待复习 */
  nextReviewAt?: number
  updatedAt?: number
}

/** 生词复习统计（课程维度，对应后端 get_vocabulary_stats） */
export interface VocabularyStats {
  courseId?: string
  total: number
  /** 已到期且未掌握 */
  due: number
  /** 已标记掌握 */
  memorized: number
  /** 至少复习过一次 */
  learned?: number
  /** 今天复习过的词数（不含只是今天采集、但一次没复习的词） */
  reviewedToday: number
  /** 未掌握且未到期的「学习中」词数 = total - memorized - due */
  learning?: number
  /** 平均难度因子 */
  avgEfactor?: number
  /** 掌握率 0~1 */
  masteryRate?: number
  now?: number
}

