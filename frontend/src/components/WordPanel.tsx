import { useState, useEffect } from 'react'
import { useSubtitleStore } from '../stores/useSubtitleStore'
import { X, Volume2, Bookmark, BookmarkCheck, Loader2, ExternalLink, Plus, CalendarClock } from 'lucide-react'
import type { VocabularyEntry } from '../types'
import { vocabularyApi } from '../lib/vocabularyApi'
import { formatNextReview, isDue } from '../lib/sm2'

interface Props {
  word: string
  courseId: string
}

export default function WordPanel({ word, courseId }: Props) {
  const { wordEntry, closeWordPanel, subtitleLines, currentText } = useSubtitleStore()
  const [loading, setLoading] = useState(false)
  const [entry, setEntry] = useState<VocabularyEntry | null>(null)
  const [collecting, setCollecting] = useState(false)
  const [collectError, setCollectError] = useState<string | null>(null)

  useEffect(() => {
    setEntry(wordEntry)
    setCollectError(null)
    if (!wordEntry) {
      fetchWord()
    }
    // wordEntry 只在点词时更新，这里按 word 重新取一次保证切换词条时不残留上一条
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [word, wordEntry])

  const fetchWord = async () => {
    setLoading(true)
    try {
      const res = await fetch(`/api/courses/${courseId}/vocabulary/${word}`)
      if (res.ok) {
        setEntry(await res.json())
      }
    } catch { /* ignore */ }
    setLoading(false)
  }

  /**
   * 找到这个词出现的原句
   *
   * 为什么要费这个劲：生词脱离了上下文就只剩一个孤立的中文释义，
   * 复习时看到「convolution → 卷积」完全想不起它出现在哪、为什么重要。
   * 把原句一起存进生词本，复习卡片才有价值。
   */
  const contextFor = (): string => {
    const needle = word.toLowerCase()
    const all = [...subtitleLines.map((l) => l.text), currentText].filter(Boolean)
    for (let i = all.length - 1; i >= 0; i--) {
      if (all[i].toLowerCase().includes(needle)) return all[i]
    }
    return ''
  }

  /** 划词采集：把当前词收进生词本（重复采集只更新释义/上下文，保留复习进度） */
  const collect = async () => {
    setCollecting(true)
    setCollectError(null)
    try {
      const created = await vocabularyApi.collect(courseId, word, {
        contextSentence: contextFor(),
        isAutoGenerated: false,
      })
      setEntry(created)
    } catch (err) {
      setCollectError(err instanceof Error ? err.message : String(err))
    } finally {
      setCollecting(false)
    }
  }

  const toggleMemorized = async () => {
    if (!entry) return
    const updated = { ...entry, isMemorized: !entry.isMemorized }
    await fetch(`/api/courses/${courseId}/vocabulary/${entry.id}`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(updated),
    })
    setEntry(updated)
  }

  return (
    <div style={styles.panel}>
      <div style={styles.header}>
        <div style={styles.headerLeft}>
          <Volume2 size={16} color="var(--accent-light)" />
          <span style={styles.headerTitle}>单词详情</span>
        </div>
        <button onClick={closeWordPanel} style={styles.closeBtn}>
          <X size={16} />
        </button>
      </div>

      <div style={styles.body}>
        {loading ? (
          <div style={styles.loading}>
            <Loader2 size={20} style={{ animation: 'spin 1s linear infinite' }} />
            <span>查询中...</span>
          </div>
        ) : entry ? (
          <>
            <div style={styles.wordHeader}>
              <h2 style={styles.word}>{entry.word}</h2>
              <button onClick={toggleMemorized} style={styles.bookmarkBtn}>
                {entry.isMemorized ? (
                  <BookmarkCheck size={18} color="var(--success)" />
                ) : (
                  <Bookmark size={18} color="var(--text-muted)" />
                )}
              </button>
            </div>

            <div style={styles.section}>
              <div style={styles.sectionLabel}>释义</div>
              <div style={styles.translation}>{entry.translation}</div>
            </div>

            {entry.definition && (
              <div style={styles.section}>
                <div style={styles.sectionLabel}>详细定义</div>
                <div style={styles.definition}>{entry.definition}</div>
              </div>
            )}

            {entry.contextSentence && (
              <div style={styles.section}>
                <div style={styles.sectionLabel}>课程原文</div>
                <div style={styles.contextSentence}>
                  "{entry.contextSentence}"
                </div>
              </div>
            )}

            <div style={styles.metaRow}>
              {entry.domain && <span style={styles.metaTag}>{entry.domain}</span>}
              {entry.isAutoGenerated && <span style={styles.aiTag}>AI 生成</span>}
              {!entry.isMemorized && (
                <span
                  style={{
                    ...styles.reviewTag,
                    color: isDue(entry.nextReviewAt, Date.now()) ? 'var(--warning)' : 'var(--text-muted)',
                  }}
                >
                  <CalendarClock size={10} />
                  {isDue(entry.nextReviewAt, Date.now())
                    ? '待复习'
                    : formatNextReview(entry.nextReviewAt, Date.now())}
                </span>
              )}
            </div>

            <div style={styles.actions}>
              <button style={styles.actionLink} onClick={() => {
                window.open(`https://www.merriam-webster.com/dictionary/${entry.word}`, '_blank')
              }}>
                <ExternalLink size={14} /> Merriam-Webster
              </button>
              <button style={styles.actionLink} onClick={() => {
                window.open(`https://dict.youdao.com/search?q=${entry.word}`, '_blank')
              }}>
                <ExternalLink size={14} /> 有道词典
              </button>
            </div>
          </>
        ) : (
          <div style={styles.notFound}>
            <p style={styles.notFoundWord}>"{word}"</p>
            <p style={styles.notFoundHint}>该词尚未收录到课程词典</p>
            <p style={styles.notFoundHint}>
              AI 也会在识别过程中自动提取术语；想立刻记下来就点下面的按钮
            </p>
            {/* 划词采集入口：这是「生词复习闭环」的起点。
                没有它的话，生词本只能靠 AI 自动提取，用户完全无法主动加词。 */}
            <button
              style={{ ...styles.collectBtn, opacity: collecting ? 0.6 : 1 }}
              disabled={collecting}
              onClick={() => void collect()}
            >
              {collecting ? (
                <>
                  <Loader2 size={14} style={{ animation: 'spin 1s linear infinite' }} /> 正在加入...
                </>
              ) : (
                <>
                  <Plus size={14} /> 加入生词本
                </>
              )}
            </button>
            {collectError && <p style={styles.collectError}>加入失败：{collectError}</p>}
            <button style={styles.lookupBtn} onClick={() => {
              window.open(`https://dict.youdao.com/search?q=${word}`, '_blank')
            }}>
              <ExternalLink size={14} /> 在有道词典中查看
            </button>
          </div>
        )}
      </div>
    </div>
  )
}

