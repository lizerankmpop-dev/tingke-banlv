import { useState, useEffect } from 'react'
import { useSubtitleStore } from '../stores/useSubtitleStore'
import { X, Volume2, Bookmark, BookmarkCheck, Loader2, ExternalLink } from 'lucide-react'
import type { VocabularyEntry } from '../types'

interface Props {
  word: string
  courseId: string
}

export default function WordPanel({ word, courseId }: Props) {
  const { wordEntry, closeWordPanel } = useSubtitleStore()
  const [loading, setLoading] = useState(false)
  const [entry, setEntry] = useState<VocabularyEntry | null>(null)

  useEffect(() => {
    setEntry(wordEntry)
    if (!wordEntry) {
      fetchWord()
    }
  }, [word, wordEntry])

  const fetchWord = async () => {
    setLoading(true)
    try {
      const res = await fetch(`/api/courses/${courseId}/vocabulary/${word}`)
      if (res.ok) {
        setEntry(await res.json())
      }
    } catch { /* ignore */ }
    setLoading(false)
  }

  const toggleMemorized = async () => {
    if (!entry) return
    const updated = { ...entry, isMemorized: !entry.isMemorized }
    await fetch(`/api/courses/${courseId}/vocabulary/${entry.id}`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(updated),
    })
    setEntry(updated)
  }

  return (
    <div style={styles.panel}>
      <div style={styles.header}>
        <div style={styles.headerLeft}>
          <Volume2 size={16} color="var(--accent-light)" />
          <span style={styles.headerTitle}>单词详情</span>
        </div>
        <button onClick={closeWordPanel} style={styles.closeBtn}>
          <X size={16} />
        </button>
      </div>

      <div style={styles.body}>
        {loading ? (
          <div style={styles.loading}>
            <Loader2 size={20} style={{ animation: 'spin 1s linear infinite' }} />
            <span>查询中...</span>
          </div>
        ) : entry ? (
          <>
            <div style={styles.wordHeader}>
              <h2 style={styles.word}>{entry.word}</h2>
              <button onClick={toggleMemorized} style={styles.bookmarkBtn}>
                {entry.isMemorized ? (
                  <BookmarkCheck size={18} color="var(--success)" />
                ) : (
                  <Bookmark size={18} color="var(--text-muted)" />
                )}
              </button>
            </div>

            <div style={styles.section}>
              <div style={styles.sectionLabel}>释义</div>
              <div style={styles.translation}>{entry.translation}</div>
            </div>

            {entry.definition && (
              <div style={styles.section}>
                <div style={styles.sectionLabel}>详细定义</div>
                <div style={styles.definition}>{entry.definition}</div>
              </div>
            )}

            {entry.contextSentence && (
              <div style={styles.section}>
                <div style={styles.sectionLabel}>课程原文</div>
                <div style={styles.contextSentence}>
                  "{entry.contextSentence}"
                </div>
              </div>
            )}

            <div style={styles.metaRow}>
              {entry.domain && <span style={styles.metaTag}>{entry.domain}</span>}
              {entry.isAutoGenerated && <span style={styles.aiTag}>AI 生成</span>}
            </div>

            <div style={styles.actions}>
              <button style={styles.actionLink} onClick={() => {
                window.open(`https://www.merriam-webster.com/dictionary/${entry.word}`, '_blank')
              }}>
                <ExternalLink size={14} /> Merriam-Webster
              </button>
              <button style={styles.actionLink} onClick={() => {
                window.open(`https://dict.youdao.com/search?q=${entry.word}`, '_blank')
              }}>
                <ExternalLink size={14} /> 有道词典
              </button>
            </div>
          </>
        ) : (
          <div style={styles.notFound}>
            <p style={styles.notFoundWord}>"{word}"</p>
            <p style={styles.notFoundHint}>该词尚未收录到课程词典</p>
            <p style={styles.notFoundHint}>AI 将在识别过程中自动提取</p>
            <button style={styles.lookupBtn} onClick={() => {
              window.open(`https://dict.youdao.com/search?q=${word}`, '_blank')
            }}>
              <ExternalLink size={14} /> 在有道词典中查看
            </button>
          </div>
        )}
      </div>
    </div>
  )
}

const styles: Record<string, React.CSSProperties> = {
  panel: { display: 'flex', flexDirection: 'column', height: '100%' },
  header: {
    display: 'flex', justifyContent: 'space-between', alignItems: 'center',
    padding: '14px 16px', borderBottom: '1px solid var(--border)', flexShrink: 0,
  },
  headerLeft: { display: 'flex', alignItems: 'center', gap: 8 },
  headerTitle: { fontSize: 14, fontWeight: 600 },
  closeBtn: { background: 'none', color: 'var(--text-muted)', padding: 4, borderRadius: 4 },
  body: { flex: 1, overflow: 'auto', padding: 16 },
  loading: {
    display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 8,
    color: 'var(--text-muted)', marginTop: 60,
  },

  // Found
  wordHeader: { display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 16 },
  word: { fontSize: 22, fontWeight: 700 },
  bookmarkBtn: { background: 'none', padding: 4 },
  section: { marginBottom: 16 },
  sectionLabel: { fontSize: 11, fontWeight: 600, color: 'var(--text-muted)', textTransform: 'uppercase', marginBottom: 6 },
  translation: { fontSize: 16, color: 'var(--accent-light)', fontWeight: 500 },
  definition: { fontSize: 13, color: 'var(--text-secondary)', lineHeight: 1.7 },
  contextSentence: { fontSize: 13, color: 'var(--text-secondary)', fontStyle: 'italic', lineHeight: 1.6 },
  metaRow: { display: 'flex', gap: 8, marginTop: 12 },
  metaTag: {
    background: 'var(--bg-tertiary)', color: 'var(--text-secondary)',
    padding: '3px 10px', borderRadius: 10, fontSize: 11,
  },
  aiTag: {
    background: 'var(--accent-glow)', color: 'var(--accent-light)',
    padding: '3px 10px', borderRadius: 10, fontSize: 11, fontWeight: 500,
  },
  actions: { marginTop: 20, display: 'flex', flexDirection: 'column', gap: 6 },
  actionLink: {
    display: 'flex', alignItems: 'center', gap: 6,
    background: 'none', color: 'var(--accent-light)',
    fontSize: 12, padding: '6px 0',
  },

  // Not found
  notFound: { textAlign: 'center', marginTop: 60, padding: 20 },
  notFoundWord: { fontSize: 18, fontWeight: 600, color: 'var(--text-secondary)', marginBottom: 12 },
  notFoundHint: { fontSize: 13, color: 'var(--text-muted)', marginBottom: 6 },
  lookupBtn: {
    display: 'inline-flex', alignItems: 'center', gap: 6,
    marginTop: 16, padding: '8px 16px',
    background: 'var(--bg-tertiary)', color: 'var(--accent-light)',
    borderRadius: 'var(--radius-sm)', fontSize: 13,
    border: '1px solid var(--border)',
  },
}
